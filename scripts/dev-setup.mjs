// Generate local-only credentials. Never commit .env or apps/agent/.dev.vars.
import { existsSync, readFileSync, writeFileSync, mkdirSync, chmodSync } from "node:fs";
import { webcrypto as crypto } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseEnv } from "node:util";

const defaultRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const token = () => Buffer.from(crypto.getRandomValues(new Uint8Array(32))).toString("base64url");

async function hash(password) {
  const iterations = 100000;
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const key = await crypto.subtle.importKey("raw", new TextEncoder().encode(password.normalize("NFKC")), "PBKDF2", false, ["deriveBits"]);
  const bits = await crypto.subtle.deriveBits({ name: "PBKDF2", hash: "SHA-256", salt, iterations }, key, 256);
  return `pbkdf2-sha256$${iterations}$${Buffer.from(salt).toString("base64url")}$${Buffer.from(bits).toString("base64url")}`;
}

export async function setupDevelopment({ root = defaultRoot, env = process.env, force = false, log = console.log } = {}) {
  const target = join(root, "apps/agent/.dev.vars");
  if (existsSync(target) && !force) {
    log("Existing apps/agent/.dev.vars preserved. Use --force to regenerate credentials; existing PostgreSQL volumes need their original database password.");
    return;
  }
  const envPath = join(root, ".env");
  const previous = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
  const settings = { ...parseEnv(previous), ...env };
  const additions = {};
  const ensure = (key, value) => {
    if (!settings[key]) settings[key] = additions[key] = value;
    return settings[key];
  };
  const postgresPassword = ensure("POSTGRES_PASSWORD", token());
  const password = ensure("TALORYS_DEV_PASSWORD", token());
  if (!settings.DATABASE_URL) {
    const url = new URL("postgresql://talorys@127.0.0.1:5432/talorys");
    url.password = encodeURIComponent(postgresPassword);
    ensure("DATABASE_URL", url.href);
    url.pathname = "/talorys_test";
    ensure("TALORYS_TEST_DATABASE_URL", url.href);
    url.pathname = "/talorys_e2e";
    ensure("TALORYS_E2E_DATABASE_URL", url.href);
  }
  if (Object.keys(additions).length) {
    mkdirSync(root, { recursive: true });
    writeFileSync(envPath, `${previous}${previous.endsWith("\n") ? "" : "\n"}# Generated local credentials. Never commit.\n${Object.entries(additions).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join("\n")}\n`, { mode: 0o600 });
    chmodSync(envPath, 0o600);
  }
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, [
    "# Local development only. Never commit. Generated by scripts/dev-setup.mjs",
    "TALORYS_ENV=development",
    `DATABASE_URL=${JSON.stringify(settings.DATABASE_URL)}`,
    `TALORYS_MOCK_AI=${settings.TALORYS_MOCK_AI ?? "1"}`,
    "TALORYS_DEV_ORIGINS=http://localhost:5173,http://127.0.0.1:5173",
    `OWNER_PASSWORD_HASH=${await hash(password)}`,
    `SESSION_SECRET=${token()}`,
    "",
  ].join("\n"), { mode: 0o600 });
  chmodSync(target, 0o600);
  log("Local credentials are configured. Your login password is TALORYS_DEV_PASSWORD in .env, or the environment value you supplied. Keep these files private.");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await setupDevelopment({ force: process.argv.includes("--force") });
}
